"""Writes frontend/src/app/feature-schema.ts from the saved model bundle.

Run after retraining so the Angular form always matches the model's raw input schema:
    python backend\\export_schema.py
"""
from pathlib import Path
import json
import joblib

ROOT = Path(__file__).resolve().parent.parent
bundle = joblib.load(ROOT / "backend/models/model_bundle.joblib")
sample = json.loads((ROOT / "backend/test_payload.json").read_text(encoding="utf-8"))

LABELS = {
    "duration": "Duration (seconds)",
    "protocol_type": "Protocol type",
    "service": "Destination service",
    "flag": "Connection status flag",
    "src_bytes": "Bytes sent (source → destination)",
    "dst_bytes": "Bytes received (destination → source)",
    "land": "Land (same host/port, 0/1)",
    "wrong_fragment": "Wrong fragments",
    "urgent": "Urgent packets",
    "hot": "Hot indicators",
    "num_failed_logins": "Failed login attempts",
    "logged_in": "Logged in (0/1)",
    "num_compromised": "Compromised conditions",
    "root_shell": "Root shell obtained (0/1)",
    "su_attempted": "su root attempted",
    "num_root": "Root accesses",
    "num_file_creations": "File creations",
    "num_shells": "Shell prompts",
    "num_access_files": "Access-control file operations",
    "is_host_login": "Host login (0/1)",
    "is_guest_login": "Guest login (0/1)",
    "count": "Connections to same host (2 s)",
    "srv_count": "Connections to same service (2 s)",
}
GROUPS = [
    ("Basic connection", ["duration", "protocol_type", "service", "flag", "src_bytes",
                          "dst_bytes", "land", "wrong_fragment", "urgent"]),
    ("Content (session behaviour)", ["hot", "num_failed_logins", "logged_in", "num_compromised",
                                     "root_shell", "su_attempted", "num_root",
                                     "num_file_creations", "num_shells", "num_access_files",
                                     "is_host_login", "is_guest_login"]),
    ("Time-based traffic (last 2 seconds)", ["count", "srv_count", "serror_rate",
                                             "srv_serror_rate", "rerror_rate", "srv_rerror_rate",
                                             "same_srv_rate", "diff_srv_rate",
                                             "srv_diff_host_rate"]),
]
group_of = {name: group for group, names in GROUPS for name in names}

fields = []
for spec in bundle["schema"]:
    name = spec["name"]
    field = {"name": name,
             "label": LABELS.get(name, spec["label"].replace("Dst host", "Dest. host")
                                 .replace("srv", "service").replace("Srv", "Service")),
             "group": group_of.get(name, "Host-based traffic (last 100 connections)"),
             "kind": spec["kind"], "required": True}
    for key in ("options", "min", "max"):
        if key in spec:
            field[key] = spec[key]
    fields.append(field)

assert [f["name"] for f in fields] == bundle["features"], "schema order must match features"

ts = f"""// GENERATED by backend/export_schema.py from backend/models/model_bundle.joblib.
// Do not edit by hand: retrain / re-export instead so the form matches the model.
export type Feature = {{
  name: string;
  label: string;
  group: string;
  kind: 'number' | 'category';
  required: boolean;
  options?: string[];
  min?: number;
  max?: number;
}};

export const MODEL_VERSION = {json.dumps(bundle["model_version"])};

// Every raw input field expected by the model, in training order ({len(fields)} features).
export const FEATURES: Feature[] = {json.dumps(fields, indent=2)};

// Non-sensitive sample record (same values as backend/test_payload.json).
export const SAMPLE_RECORD: Record<string, string | number> = {json.dumps(sample, indent=2)};
"""
out = ROOT / "frontend/src/app/feature-schema.ts"
out.write_text(ts, encoding="utf-8")
print(f"Wrote {out.relative_to(ROOT).as_posix()} with {len(fields)} features")
